def parse_frontmatter(content):
    """Parse YAML frontmatter and body from a transcript file.
    Returns (frontmatter_text, frontmatter_dict, body)."""
    if not content.startswith("---"):
        return "", {}, content

    parts = content.split("---", 2)
    if len(parts) < 3:
        return "", {}, content

    fm_text = parts[1].strip()
    body = parts[2].strip()

    fm_dict = {}
    for line in fm_text.split("\n"):
        line = line.strip()
        if ":" in line and not line.startswith("#") and not line.startswith("-"):
            key, _, val = line.partition(":")
            fm_dict[key.strip()] = val.strip()

    return fm_text, fm_dict, body


def rebuild_file(fm_text, summary, formatted_body, title=None, original_title_line=None):
    """Rebuild the transcript file with formatting: cleaned added."""
    if "formatting:" not in fm_text:
        fm_text += "\nformatting: cleaned"
    else:
        fm_text = re.sub(r"formatting:.*", "formatting: cleaned", fm_text)

    parts = [f"---\n{fm_text}\n---\n"]

    if summary:
        parts.append(f"\n{summary}\n")

    if title:
        parts.append(f"\n# {title}\n")
    elif original_title_line:
        parts.append(f"\n{original_title_line}\n")

    if formatted_body:
        parts.append(f"\n{formatted_body}\n")

    return "\n".join(parts)


def detect_type(fm_dict):
    """Detect transcript type from frontmatter fields."""
    method = fm_dict.get("transcription_method", "")
    tool = fm_dict.get("transcription_tool", "")

    if "AssemblyAI" in tool or "Whisper" in tool:
        return "audio"
    if "ai-vision" in method or "native" in method or "ocr" in method:
        return "pdf"
    return "pdf"


CHUNK_WORD_LIMIT = 8000  # split large transcripts into chunks of ~8000 words


def split_into_chunks(body):
    """Split a transcript body into chunks by page markers, staying under word limit."""
    # Split by page markers
    page_pattern = re.compile(r"(?=\n## Page \d+)")
    pages = page_pattern.split(body)
    pages = [p for p in pages if p.strip()]

    if not pages:
        return [body]

    chunks = []
    current_chunk = []
    current_words = 0

    for page in pages:
        page_words = len(page.split())
        if current_words + page_words > CHUNK_WORD_LIMIT and current_chunk:
            chunks.append("\n".join(current_chunk))
            current_chunk = [page]
            current_words = page_words
        else:
            current_chunk.append(page)
            current_words += page_words

    if current_chunk:
        chunks.append("\n".join(current_chunk))

    return chunks


